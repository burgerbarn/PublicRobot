"""Generate ros2/rosorin_base/urdf/rosorin.urdf from model/robot_model.json (factory URDF numbers,
measured 2026-09-27). Kinematics + box collision geometry (same boxes as arm_model.py; no meshes). Root = base_link (EKF owns odom->base_link).
LiDAR/IMU frames stay as static TFs in base.launch.py (names laser/imu_link).
camera_link -> depth_camera_link: optical rotation rpy(-pi/2, 0, -pi/2), as factory
(depth_camera.urdf.xacro depth_cam_joint_sim / aurora930.launch.py static TF). The Deptrum node
itself publishes depth_camera_link -> rgb_camera_link from the camera's stored extrinsics."""
import json, math, os

HERE = os.path.dirname(os.path.abspath(__file__))
m = json.load(open(os.path.join(HERE, 'robot_model.json')))
J = m['joints']
KEEP = ['joint1', 'joint2', 'joint3', 'joint4', 'joint5', 'gripper_joint', 'end_effector_joint',
        'camera_connect_joint', 'camera_joint']
f = lambda v: ' '.join(f'{x:.6g}' for x in v)
links = {'base_link'}
out = ['<?xml version="1.0"?>', '<!-- GENERATED by model/make_urdf.py from model/robot_model.json - do not edit -->',
       '<robot name="rosorin">', '  <link name="base_link"/>']
for name in KEEP:
    j = J[name]
    for l in (j['parent'], j['child']):
        if l not in links:
            links.add(l); out.append(f'  <link name="{l}"/>')
    out.append(f'  <joint name="{name}" type="{j["type"]}">')
    out.append(f'    <parent link="{j["parent"]}"/><child link="{j["child"]}"/>')
    out.append(f'    <origin xyz="{f(j["xyz"])}" rpy="{f(j["rpy"])}"/>')
    if j['type'] == 'revolute':
        out.append(f'    <axis xyz="{f(j["axis"])}"/>')
        lo, hi = j['limit']
        out.append(f'    <limit lower="{lo}" upper="{hi}" effort="1.0" velocity="1.0"/>')
    out.append('  </joint>')
# ---- collision geometry (2026-09-29, for MoveIt): the SAME boxes arm_model.py checks with.
# Arm/camera boxes are axis-aligned in their link frames; the chassis height map (base_footprint frame, 1 cm cells)
# becomes run-length-merged boxes per row; the LiDAR box moves into base_link through lidar_joint (yaw pi).
def box_xml(lo, hi):
    c = [(a + b) / 2 for a, b in zip(lo, hi)]; sz = [max(b - a, 1e-3) for a, b in zip(lo, hi)]
    return f'    <collision><origin xyz="{f(c)}" rpy="0 0 0"/><geometry><box size="{f(sz)}"/></geometry></collision>'
coll = {l: [] for l in links}
for l, b in m['boxes'].items():
    if l in coll:
        coll[l].append(box_xml(b['min'], b['max']))
lj, lb = J['lidar_joint'], m['boxes']['lidar_frame']                  # yaw pi: (x, y) -> (-x, -y)
coll['base_link'].append(box_xml([lj['xyz'][0] - lb['max'][0], lj['xyz'][1] - lb['max'][1], lj['xyz'][2] + lb['min'][2]],
                                 [lj['xyz'][0] - lb['min'][0], lj['xyz'][1] - lb['min'][1], lj['xyz'][2] + lb['max'][2]]))
hm = m['chassis_heightmap']; ox, oy = hm['origin_xy']; cell = hm['cell']; dz = J['base_joint']['xyz'][2]
n_chassis = 0
for i, row in enumerate(hm['z']):
    q = [math.ceil(z * 100) / 100 if z > 0 else 0 for z in row]      # 1 cm steps, rounded UP (conservative)
    j = 0
    while j < len(q):
        k = j
        while k + 1 < len(q) and q[k + 1] == q[j]:
            k += 1
        if q[j] > 0:
            coll['base_link'].append(box_xml([ox + i * cell, oy + j * cell, -dz], [ox + (i + 1) * cell, oy + (k + 1) * cell, q[j] - dz]))
            n_chassis += 1
        j = k + 1
for i, line in enumerate(out):                                          # expand '<link name="x"/>' with collisions
    for l, c in coll.items():
        if c and line == f'  <link name="{l}"/>':
            out[i] = '\n'.join([f'  <link name="{l}">'] + c + ['  </link>'])
print('collision boxes:', {l: len(c) for l, c in coll.items() if c}, f'(chassis {n_chassis})')
out += ['  <link name="depth_camera_link"/>',
        '  <joint name="camera_optical_joint" type="fixed">',
        '    <parent link="camera_link"/><child link="depth_camera_link"/>',
        f'    <origin xyz="0 0 0" rpy="{-math.pi / 2:.6f} 0 {-math.pi / 2:.6f}"/>',
        '  </joint>', '</robot>', '']
dst = os.path.join(HERE, '..', 'ros2', 'rosorin_base', 'urdf', 'rosorin.urdf')
os.makedirs(os.path.dirname(dst), exist_ok=True)
open(dst, 'w').write('\n'.join(out))
print('wrote', os.path.normpath(dst), len(links), 'links')
